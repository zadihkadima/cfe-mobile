const plugin = require("tailwindcss/plugin");

const {
  tailwindColors,
  cssVariables,
  DEFAULT_THEME,
} = require("./src/design-system/theme/palette");

module.exports = {

  darkMode: "class",

  content: [
    "./src/**/*.{js,jsx,ts,tsx}",
  ],

  presets: [
    require("nativewind/preset"),
  ],

  theme: {

    extend: {

      // Generated from the palette rather than written out here. The previous
      // hand-maintained copy had already drifted from the TypeScript one
      // (`elevated` disagreed in both themes), and it omitted `divider`,
      // `overlay` and the brand light/dark variants entirely, so those tokens
      // existed but could not be reached from a class name. Generating the map
      // makes both problems structurally impossible rather than relying on two
      // lists being kept in step by hand.
      //
      // Each entry now resolves to `rgb(var(--color-token) / <alpha-value>)`
      // rather than to a hex value, so the colour a class name produces is
      // decided at runtime by whichever theme is selected. Without that
      // indirection a theme could only reach the ~21 files that read
      // `theme.colors` in JavaScript, leaving the ~99 styled with class names
      // showing whatever palette happened to be compiled in.
      colors: tailwindColors(),

    },

  },

  plugins: [

    // Seeds `:root` with the default theme's variables.
    //
    // This is what the application looks like before any JavaScript runs, and
    // what it falls back to if the provider is ever absent from the tree -- an
    // unstyled first frame rather than a transparent one. It is generated by
    // the same function the provider calls, so the compiled defaults cannot
    // describe a different palette from the one assigned at runtime.
    plugin(function seedDefaultTheme({ addBase }) {
      addBase({
        ":root": {
          ...cssVariables(DEFAULT_THEME, "light"),
          ...cssVariables(DEFAULT_THEME, "dark"),
        },
      });
    }),

  ],

};
